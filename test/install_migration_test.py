import os
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPT = (Path(__file__).resolve().parents[1] / "install.sh").read_text(encoding="utf-8")
FUNCTIONS = SCRIPT.split("# Quota migration functions")[1].split("\nquota_only_dropin()", 1)[1]
FUNCTIONS = "quota_only_dropin()" + FUNCTIONS.split("# End quota migration functions.")[0]


class QuotaMigrationTest(unittest.TestCase):
    def run_migration(self, files, loaded=None, fragment=""):
        with tempfile.TemporaryDirectory(prefix="governor-quota-test-") as directory:
            root = Path(directory)
            (root / "var/backups").mkdir(parents=True)
            for name, content in files.items():
                path = root / name.lstrip("/")
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
            body = FUNCTIONS.replace("/etc/systemd/", f"{root}/etc/systemd/").replace(
                "/var/backups/", f"{root}/var/backups/"
            )
            body = (
                'set -euo pipefail\nsystemctl() { case "$*" in *DropInPaths*) printf "%s" "$QUOTA_PATHS";; *FragmentPath*) printf "%s" "$QUOTA_FRAGMENT";; esac; }\n'
                + body
                + "\nfind_persistent_quotas\nretire_persistent_quotas\n"
            )
            result = subprocess.run(
                ["bash", "-c", body],
                capture_output=True,
                text=True,
                env={
                    **os.environ,
                    "QUOTA_PATHS": " ".join(str(root / p.lstrip("/")) for p in (loaded or [])),
                    "QUOTA_FRAGMENT": str(root / fragment.lstrip("/")) if fragment else "",
                },
            )
            remaining = {name: (root / name.lstrip("/")).exists() for name in files}
            backups = [
                p.read_text(encoding="utf-8") for p in (root / "var/backups").rglob("*.conf")
            ]
            return result, remaining, backups

    def test_generated_persistent_cap_is_archived_and_unrelated_settings_kept(self):
        cap = "/etc/systemd/system.control/user.slice.d/50-CPUQuota.conf"
        memory = "/etc/systemd/system/user.slice.d/40-memory.conf"
        contents = "# generated by systemctl\n[Slice]\nCPUQuota=780%\n"
        result, remaining, backups = self.run_migration(
            {cap: contents, memory: "[Slice]\nMemoryMax=6G\n"}, [cap, memory]
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(remaining[cap])
        self.assertTrue(remaining[memory])
        self.assertEqual(backups, [contents])
        self.assertIn("recoverable at", result.stdout)

    def test_shadowed_caps_are_also_retired(self):
        paths = [
            "/etc/systemd/system.control/user.slice.d/50-CPUQuota.conf",
            "/etc/systemd/system/user.slice.d/50-CPUQuota.conf",
        ]
        result, remaining, backups = self.run_migration(
            dict.fromkeys(paths, "[Slice]\nCPUQuota=560%\n"), [paths[0]]
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(any(remaining.values()))
        self.assertEqual(len(backups), 2)

    def test_mixed_file_fails_before_migrating_anything(self):
        first = "/etc/systemd/system.control/user.slice.d/50-CPUQuota.conf"
        mixed = "/etc/systemd/system/user.slice.d/90-local.conf"
        result, remaining, backups = self.run_migration(
            {first: "[Slice]\nCPUQuota=780%\n", mixed: "[Slice]\nCPUQuota=200%\nMemoryMax=6G\n"},
            [first, mixed],
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("remove only CPUQuota", result.stderr)
        self.assertTrue(all(remaining.values()))
        self.assertEqual(backups, [])

    def test_main_unit_quota_requires_manual_change(self):
        unit = "/etc/systemd/system/user.slice"
        result, remaining, _ = self.run_migration(
            {unit: "[Slice]\nCPUQuota=800%\nMemoryMax=6G\n"}, fragment=unit
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(remaining[unit])

    def test_owned_fallback_is_left_for_installer_and_no_conflicts_succeed(self):
        own = "/etc/systemd/system/user.slice.d/10-governor.conf"
        result, remaining, backups = self.run_migration(
            {own: "[Slice]\nCPUAccounting=yes\nCPUQuota=20%\n"}, [own]
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(remaining[own])
        self.assertEqual(backups, [])
        self.assertEqual(self.run_migration({})[0].returncode, 0)


if __name__ == "__main__":
    unittest.main()
